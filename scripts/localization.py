#!/usr/bin/env python3
"""Pawverio translation pipeline. Never sends pet data; catalog text only.

python scripts/localization.py generate
python scripts/localization.py validate
python scripts/localization.py extract
python scripts/localization.py translate --locale fr-FR
python scripts/localization.py review --locale fr-FR --reviewer NAME

Translation API: explicitly set PAWVERIO_TRANSLATION_URL and
PAWVERIO_TRANSLATION_KEY. POST JSON {source,target,text,glossary}; expect
{translation: string}. Credentials are host-only and never emitted to resources.
"""
import argparse
import csv
import hashlib
import json
import os
import re
import sys
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
LOC = ROOT / 'localization'
CATALOG = LOC / 'catalog.json'
LOCALES = ['en-GB','en-US','en-AU','es-ES','es-419','fr-FR','fr-CA','de-DE','it-IT','pt-BR','pt-PT','nl-NL','pl-PL','sv-SE','ja-JP','hi-IN','ar','tr-TR','id-ID']
SHARED = {'en-GB':'en','en-US':'en','en-AU':'en','fr-CA':'fr-FR','es-419':'es-ES'}
PH = re.compile(r'%(?:\d+\$)?[dsf]|\{[a-zA-Z_]\w*\}')
# CLDR cardinal categories, not ordinal categories:
# https://www.unicode.org/cldr/charts/latest/supplemental/language_plural_rules.html
# es/fr/it/pt include many for million-scale values; ja/id have only other.
QUANTITIES = {
    'ar':['zero','one','two','few','many','other'],
    'pl-PL':['one','few','many','other'],
    'es-ES':['one','many','other'], 'es-419':['one','many','other'],
    'fr-FR':['one','many','other'], 'fr-CA':['one','many','other'],
    'it-IT':['one','many','other'],
    'pt-BR':['one','many','other'], 'pt-PT':['one','many','other'],
    'ja-JP':['other'], 'id-ID':['other']
}

def read(path):
    return json.loads(path.read_text(encoding='utf-8'))

def write(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2)+'\n',encoding='utf-8')

def dictionary(locale):
    explicit = LOC / 'translations' / (locale + '.json')
    if explicit.exists():
        return read(explicit)
    source = SHARED.get(locale, locale)
    if source == 'en':
        return read(CATALOG)
    path = LOC / 'translations' / (source + '.json')
    return read(path) if path.exists() else {}

def qualifier(locale):
    # Android lint/aapt use the historical Indonesian resource language alias.
    # Public application locale remains the modern BCP47 tag id-ID.
    if locale == 'id-ID':
        return 'values-in-rID'
    return 'values-b+' + locale.replace('-', '+')

def android_escape(value):
    # Quote entire Android resource to preserve whitespace, protect apostrophes.
    return '"' + escape(value.replace('\\','\\\\').replace('"','\\"').replace("'", "\\'")).replace('\n', '\\n') + '"'

def generate():
    catalog = read(CATALOG)
    for locale in ['default'] + LOCALES:
        values = catalog if locale == 'default' else dictionary(locale)
        missing = sorted(set(catalog)-set(values))
        if missing:
            raise ValueError(f'{locale}: missing {len(missing)} strings: {missing}')
        out = ROOT/'app/src/main/res'/('values' if locale == 'default' else qualifier(locale))/'strings.xml'
        out.parent.mkdir(parents=True, exist_ok=True)
        lines = ['<?xml version="1.0" encoding="utf-8"?>','<!-- Generated by scripts/localization.py. AI-authored translations; human review pending. -->','<resources>']
        for key, value in values.items():
            lines.append(f'    <string name="{key}">{android_escape(value)}</string>')
        plural_path = LOC/'plurals.json'
        plurals = read(plural_path) if plural_path.exists() else {}
        forms = plurals.get(locale, {})
        lines.append('    <plurals name="tasks_count">')
        for quantity in QUANTITIES.get(locale,['one','other']):
            text = forms.get(quantity, values['tasks_count_one' if quantity == 'one' else 'tasks_count_other'])
            lines.append(f'        <item quantity="{quantity}">{android_escape(text)}</item>')
        lines.extend(['    </plurals>','</resources>'])
        out.write_text('\n'.join(lines)+'\n',encoding='utf-8')
    fixture_keys=['nav_today','nav_pets','nav_health','voice_title','sitter_mode','privacy_body']
    fixture={locale:{key:dictionary(locale)[key] for key in fixture_keys} for locale in LOCALES}
    write(ROOT/'app/src/androidTest/assets/locale-expectations.json',fixture)
    print(f'Generated {len(LOCALES)} locale resources plus reliable English fallback.')

def validate():
    catalog = read(CATALOG)
    rows, errors = [], []
    for locale in LOCALES:
        strings = dictionary(locale)
        missing = sorted(set(catalog)-set(strings))
        extra = sorted(set(strings)-set(catalog))
        for key in set(catalog) & set(strings):
            if sorted(PH.findall(catalog[key])) != sorted(PH.findall(strings[key])):
                errors.append(f'{locale}:{key}: placeholder mismatch')
            if not strings[key].strip(): errors.append(f'{locale}:{key}: empty string')
        errors += [f'{locale}: missing {key}' for key in missing]
        errors += [f'{locale}: unknown {key}' for key in extra]
        resource = ROOT/'app/src/main/res'/qualifier(locale)/'strings.xml'
        try:
            tree = ET.parse(resource)
            names = [node.attrib.get('name') for node in tree.getroot()]
            if len(names) != len(set(names)): errors.append(f'{locale}: duplicate resource name')
            plural = tree.find(".//plurals[@name='tasks_count']")
            expected = set(QUANTITIES.get(locale,['one','other']))
            if plural is None or {n.attrib['quantity'] for n in plural} != expected:
                errors.append(f'{locale}: plural categories missing')
        except (OSError, ET.ParseError) as exc:
            errors.append(f'{locale}: invalid XML: {exc}')
        review_path = LOC/'reviews'/f'{locale}.json'
        review = read(review_path) if review_path.exists() else {'status':'PENDING_HUMAN_REVIEW'}
        digest=hashlib.sha256(json.dumps(strings,ensure_ascii=False,sort_keys=True).encode()).hexdigest()
        if review.get('status')=='HUMAN_REVIEWED' and review.get('catalog_sha256')!=digest:
            review={'status':'STALE_REVIEW'}
        rows.append({'locale':locale,'source_strings':len(catalog),'present':len(set(catalog)&set(strings)),'missing':len(missing),'coverage_percent':round(100*(len(catalog)-len(missing))/len(catalog),2),'human_review':review['status'],'layout_testing':'NOT TESTED','voice_recognition':'NOT TESTED','text_to_speech':'NOT TESTED'})
    out=LOC/'coverage.csv'
    with out.open('w',encoding='utf-8',newline='') as fh:
        writer=csv.DictWriter(fh,fieldnames=list(rows[0])); writer.writeheader();writer.writerows(rows)
    report={'result':'FAIL' if errors else 'PASS','scope':'catalog/XML/placeholder/plural structure only; no linguistic or device certification','errors':errors,'locales':rows}
    write(LOC/'validation-report.json',report)
    print(json.dumps({'result':report['result'],'errors':errors,'locales':len(rows),'strings_per_locale':len(catalog)},ensure_ascii=False))
    return 1 if errors else 0

def extract():
    """Inventory Android string references and literal Compose text for review."""
    refs=set(); literals=[];brand_literals=[]
    for path in (ROOT/'app/src').rglob('*.kt'):
        source=path.read_text(encoding='utf-8')
        refs.update(re.findall(r'R\.string\.(\w+)', source))
        for match in re.finditer(r'\b(?:Text|TextField|OutlinedTextField)\(\s*"([^"\n]+)"',source):
            item={'file':str(path.relative_to(ROOT)),'line':source.count('\n',0,match.start())+1,'text':match.group(1)}
            if match.group(1) in ['Pawverio','Pawverio Premium']:
                brand_literals.append(item)
            else:literals.append(item)
    catalog=read(CATALOG)
    report={'referenced_ids':sorted(refs),'missing_ids':sorted(refs-set(catalog)),'literal_text_candidates':literals,'nontranslatable_brand_literals':brand_literals,'scope':'Heuristic inventory of app Kotlin resource references and direct Text/TextField literals; inspect composed and platform strings separately.'}
    write(LOC/'extraction-report.json',report)
    print(json.dumps({'references':len(refs),'missing_ids':report['missing_ids'],'literal_text_candidates':len(literals)}))
    return int(bool(report['missing_ids'] or literals))

def translate(locale):
    if locale not in LOCALES: raise ValueError('Unknown locale')
    url=os.environ.get('PAWVERIO_TRANSLATION_URL')
    key=os.environ.get('PAWVERIO_TRANSLATION_KEY')
    if not url or not key: raise ValueError('Configure PAWVERIO_TRANSLATION_URL and PAWVERIO_TRANSLATION_KEY on the host; never inside the APK.')
    if not url.startswith('https://'): raise ValueError('Translation API must use HTTPS')
    catalog=read(CATALOG); glossary=read(LOC/'glossary.json'); results={}
    cache_dir=LOC/'cache'; cache_dir.mkdir(exist_ok=True)
    for identifier, text in catalog.items():
        if identifier in ('app_name','premium','date_format_hint','time_format_hint'):
            results[identifier]=text; continue
        placeholders=PH.findall(text)
        protected=text
        for index,token in enumerate(placeholders): protected=protected.replace(token,f'__PH_{index}__',1)
        digest=hashlib.sha256(json.dumps([locale,protected,glossary],ensure_ascii=False,sort_keys=True).encode()).hexdigest()
        cached=cache_dir/f'{digest}.json'
        cached_result=cached.exists()
        if cached_result: translated=read(cached)['translation']
        else:
            request=urllib.request.Request(url,data=json.dumps({'source':'en-GB','target':locale,'text':protected,'glossary':glossary}).encode(),headers={'Content-Type':'application/json','Authorization':f'Bearer {key}'})
            with urllib.request.urlopen(request,timeout=45) as response: translated=json.load(response)['translation']
            if not isinstance(translated,str): raise ValueError('API translation must be a string')
        protected_translation=translated
        for index,token in enumerate(placeholders):
            marker=f'__PH_{index}__'
            if translated.count(marker)!=1: raise ValueError(f'{identifier}: translation lost protected placeholder')
            translated=translated.replace(marker,token)
        if sorted(PH.findall(translated)) != sorted(placeholders): raise ValueError(f'{identifier}: placeholder mismatch')
        if not cached_result:write(cached,{'translation':protected_translation})
        results[identifier]=translated
    write(LOC/'translations'/f'{locale}.json',results)
    write(LOC/'reviews'/f'{locale}.json',{'status':'PENDING_HUMAN_REVIEW','provenance':'configured translation API','reviewer':None})
    print(f'Wrote {len(results)} machine-translated strings; review required.')

def review(locale, reviewer):
    if locale not in LOCALES or not reviewer: raise ValueError('Locale and named reviewer required')
    digest=hashlib.sha256(json.dumps(dictionary(locale),ensure_ascii=False,sort_keys=True).encode()).hexdigest()
    write(LOC/'reviews'/f'{locale}.json',{'status':'HUMAN_REVIEWED','reviewer':reviewer,'catalog_sha256':digest,'note':'Reviewer must also validate strings in context before release approval.'})
    print('Recorded reviewer declaration; device/layout checks remain separate.')

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('command',choices=['generate','validate','extract','translate','review']);parser.add_argument('--locale');parser.add_argument('--reviewer');args=parser.parse_args()
    try:
        if args.command=='generate': generate();return 0
        if args.command=='validate': return validate()
        if args.command=='extract': return extract()
        if args.command=='translate': translate(args.locale);return 0
        if args.command=='review': review(args.locale,args.reviewer);return 0
    except (ValueError,OSError,KeyError) as exc:
        print(f'ERROR: {exc}',file=sys.stderr);return 1

if __name__=='__main__': sys.exit(main())
